#!/usr/bin/env python3
"""
Generate g_vmp_payload_data.cpp + g_vmp_config.h from encrypted business DEX + SM4 key.

Each build gets randomized algorithm constants:
  - LCG multiplier & addend (scatter algorithm)
  - XOR multiplier (key deobfuscation formula)
  Written to g_vmp_config.h, consumed by dex-packer.cpp at compile time.

Usage:
  python3 gen_payload_cpp.py <encrypted_dex> <output_cpp> <crc32_hex> <sm4_key_hex> <seed_hex>
"""

import sys
import os
import random
from pathlib import Path


def random_odd_u32() -> int:
    """Random 32-bit odd integer (LCG requires odd multiplier for full period)."""
    return (random.randint(1, 0x7FFFFFFF) * 2 + 1) & 0xFFFFFFFF


def compute_obfuscated_key(actual_key_hex: str, xor_key_seed: int,
                           xor_mult: int, xor_stride: int) -> bytes:
    """Reverse deobfuscate_key() to produce the stored obfuscated key.
    Uses randomized constants from config. """
    actual_key = bytes.fromhex(actual_key_hex)
    seed = [
        (xor_key_seed >> 0) & 0xFF,
        (xor_key_seed >> 8) & 0xFF,
        (xor_key_seed >> 16) & 0xFF,
        (xor_key_seed >> 24) & 0xFF,
    ]
    obf = bytearray(16)
    for i in range(16):
        stride = (i * xor_stride) & 3
        mul = (i * xor_mult) & 0xFF
        obf[i] = actual_key[i] ^ seed[stride] ^ mul
    return bytes(obf)


def scatter_key_positions(seed: int, lcg_mul: int, lcg_add: int) -> list:
    """Derive 16 unique positions using randomized LCG constants."""
    positions = []
    state = seed
    for _ in range(16):
        state = (state * lcg_mul + lcg_add) & 0xFFFFFFFF
        pos = state % 240
        while pos in positions:
            pos = (pos + 1) % 240
        positions.append(pos)
    return positions


def generate_shell_names() -> dict:
    """Generate randomized Java identifiers for shell method/field names.
    Returns a dict keyed by logical name → random Java identifier.
    Each build gets different names, making static string-search useless."""
    import string as _s
    def random_java_id():
        # Valid Java identifier: starts with letter/underscore/$, alphanumeric thereafter
        prefix = random.choice('_abcdef')
        body = ''.join(random.choices(_s.ascii_letters + _s.digits, k=random.randint(10, 16)))
        return prefix + body

    names = {
        'load_payload':   random_java_id(),  # nativeLoadPayload replacement
        'dex_classloader': random_java_id(),  # sDexClassLoader field
        'real_app_class':  random_java_id(),  # sRealAppClass field
    }
    print(f"   Shell names: load_payload={names['load_payload']} "
          f"dex_cl={names['dex_classloader']} real_app={names['real_app_class']}",
          file=sys.stderr)
    return names


def generate_config(cpp_dir: Path, lcg_mul: int, lcg_add: int,
                    xor_mult: int, xor_stride: int,
                    integrity_mul: int, seed: int,
                    shell_names: dict = None) -> None:
    """Write g_vmp_config.h — consumed by dex-packer.cpp and native-bridge.cpp."""
    mask_val = xor_stride - 1  # xor_stride is always 2, 4, or 8
    # Shell name macros (empty if not provided)
    shell_macros = ""
    if shell_names:
        shell_macros = f'''
// ── Shell method/field name obfuscation (per-build random) ─────────
// These replace the hardcoded JNI names in Kotlin shell + C++ gMethods.
// C++:  RegisterNatives with VMP_SHELL_LOAD_PAYLOAD instead of "nativeLoadPayload"
//       GetStaticFieldID with VMP_SHELL_DEX_LOADER instead of "sDexClassLoader"
//       GetStaticFieldID with VMP_SHELL_REAL_APP_CLASS instead of "sRealAppClass"
// Kotlin: external fun {shell_names['load_payload']}(...) replaces nativeLoadPayload
//         @JvmStatic var {shell_names['dex_classloader']} replaces sDexClassLoader
//         @JvmStatic var {shell_names['real_app_class']} replaces sRealAppClass
#define VMP_SHELL_LOAD_PAYLOAD   "{shell_names['load_payload']}"
#define VMP_SHELL_DEX_LOADER     "{shell_names['dex_classloader']}"
#define VMP_SHELL_REAL_APP_CLASS "{shell_names['real_app_class']}"
'''
    content = f'''// Auto-generated per-build VMP configuration — DO NOT COMMIT
// Each APK build gets randomized algorithm constants.
// Generated by gen_payload_cpp.py at build time.

#ifndef YUNIAN_VMP_CONFIG_H
#define YUNIAN_VMP_CONFIG_H

#include <stdint.h>

// ── LCG parameters for scatter_key_positions ──────────────────────
// state = (state * VMP_LCG_MUL + VMP_LCG_ADD) & 0xFFFFFFFF
#define VMP_LCG_MUL  0x{lcg_mul:08X}u
#define VMP_LCG_ADD  0x{lcg_add:08X}u

// ── XOR deobfuscation parameters for deobfuscate_key ──────────────
// key_out[i] = obf_key[i] ^ seed[(i * VMP_XOR_STRIDE) & 3] ^ (i * VMP_XOR_MULT)
#define VMP_XOR_MULT    0x{xor_mult:02X}u
#define VMP_XOR_STRIDE  0x{xor_stride:02X}u

// ── Integrity seed multiplier (vm-engine.cpp vm_init) ─────────────
// Replaces hardcoded 1103515245 with per-build random value.
#define VMP_INTEGRITY_MUL  0x{integrity_mul:08X}u

// ── Seed (cert CRC32, for reference only — not used at runtime) ───
#define VMP_BUILD_SEED  0x{seed:08X}u
{shell_macros}
#endif // YUNIAN_VMP_CONFIG_H
'''
    config_path = cpp_dir / "g_vmp_config.h"
    with open(config_path, 'w') as f:
        f.write(content)
    print(f"   Config: {config_path} ({len(content)} bytes)", file=sys.stderr)
    print(f"   LCG: mul=0x{lcg_mul:08X} add=0x{lcg_add:08X}", file=sys.stderr)
    print(f"   XOR: mult=0x{xor_mult:02X} stride=0x{xor_stride:02X}", file=sys.stderr)

    # Also write shell names as JSON for build_shell_apk.py to read
    if shell_names:
        import json as _json
        names_path = cpp_dir / "g_vmp_shell_names.json"
        with open(names_path, 'w') as f:
            _json.dump(shell_names, f)
        print(f"   Shell names → {names_path}", file=sys.stderr)


