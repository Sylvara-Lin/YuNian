def generate_ss_config(cpp_dir: Path) -> None:
    """Write g_ss_config.h with per-build random SS_KEY.
    Each APK build gets a unique XOR key for the secure string table,
    making static string extraction impossible across builds."""
    ss_key = random.randint(1, 255)  # non-zero, non-trivial
    n = len(SS_STRINGS)

    # Generate XOR-encrypted C arrays
    arrays = []
    for i, plain in enumerate(SS_STRINGS):
        enc = [b ^ ss_key for b in plain.encode()]
        hex_bytes = ", ".join(f"0x{b:02X}" for b in enc)
        arrays.append(f"// ID {i}: \"{plain}\"\n"
                      f"static const uint8_t g_ss_{i}[] = {{{hex_bytes}}};\n"
                      f"#define SS_LEN_{i} {len(plain)}")

    # Build table arrays
    names = ", ".join(f"g_ss_{i}" for i in range(n))
    lens = ", ".join(f"SS_LEN_{i}" for i in range(n))

    # Build the array block (avoid backslash in f-string expression)
    array_block = "\n\n".join(arrays)

    content = f'''// Auto-generated per-build secure string table — DO NOT COMMIT
// Each APK build gets a randomized SS_KEY (XOR obfuscation).
// Generated by gen_payload_cpp.py at build time.

#ifndef YUNIAN_SS_CONFIG_H
#define YUNIAN_SS_CONFIG_H

#include <stdint.h>
#include <stddef.h>

#define SS_KEY 0x{ss_key:02X}u
#define SS_TABLE_SIZE {n}

{array_block}

static const uint8_t* g_ss_table[{n}] = {{ {names} }};
static const size_t g_ss_len_table[{n}] = {{ {lens} }};

#endif // YUNIAN_SS_CONFIG_H
'''
    config_path = cpp_dir / "g_ss_config.h"
    with open(config_path, 'w') as f:
        f.write(content)
    print(f"   SS config: {config_path} ({len(content)} bytes, key=0x{ss_key:02X})",
          file=sys.stderr)


def main():
    if len(sys.argv) < 6:
        print(f"Usage: {sys.argv[0]} <encrypted_dex> <output_cpp> <crc32_hex> <sm4_key_hex> <seed_hex>")
        sys.exit(1)

    enc_path = sys.argv[1]
    out_path = sys.argv[2]
    crc_hex = sys.argv[3] if sys.argv[3].startswith('0x') else f'0x{sys.argv[3]}'
    sm4_key_hex = sys.argv[4]
    xor_key_seed = int(sys.argv[5], 0)

    # ── Generate randomized algorithm constants ──
    lcg_mul = random_odd_u32()
    lcg_add = random.randint(1, 0xFFFFFFFF)
    xor_mult = random.randint(7, 253)       # non-zero, non-trivial
    xor_stride = random.choice([1, 2, 3, 4, 5, 7])  # coprime-ish to 4
    integrity_mul = random_odd_u32()         # random odd multiplier for integrity seed
    shell_names = generate_shell_names()     # random shell method/field names

    # Write config header
    cpp_dir = Path(out_path).parent
    generate_config(cpp_dir, lcg_mul, lcg_add, xor_mult, xor_stride,
                    integrity_mul, xor_key_seed, shell_names)

    # Write secure string table with per-build random XOR key
    generate_ss_config(cpp_dir)

    # Compute obfuscated key using randomized constants
    obf_key = compute_obfuscated_key(sm4_key_hex, xor_key_seed, xor_mult, xor_stride)

    # Scatter positions using randomized LCG
    positions = scatter_key_positions(xor_key_seed, lcg_mul, lcg_add)

    # Read encrypted payload
    with open(enc_path, 'rb') as f:
        enc_data = f.read()

    size = len(enc_data)
    print(f"Encrypted payload: {size:,} bytes, CRC32={crc_hex}, SM4 key={sm4_key_hex}",
          file=sys.stderr)

    # ── Split-key storage ──
    header_size = 256
    header = bytearray(header_size)
    for i in range(header_size):
        header[i] = random.randint(0, 255)
    for ki, pos in enumerate(positions):
        header[pos] = obf_key[ki]

    combined = bytes(header) + enc_data
    total_size = len(combined)

    # Generate C array
    lines = []
    for i in range(0, total_size, 40):
        chunk = combined[i:i + 40]
        line = "    " + ", ".join(f"0x{b:02x}" for b in chunk)
        if i + 40 < total_size:
            line += ","
        lines.append(line)

    payload_str = "\n".join(lines)

    content = f'''// Auto-generated VMP payload — shell DEX packer
// Per-build random config: see g_vmp_config.h
// Payload size: {size:,} bytes (padded to 16-byte boundary)
// Expected CRC32: {crc_hex}
// Header: {header_size} bytes (key scattered at config-derived positions)
// Actual encrypted DEX starts at offset {header_size}

#include <stdint.h>
#include <stddef.h>

#define VMP_HEADER_SIZE {header_size}

extern const uint32_t g_vmp_payload_size __attribute__((used, visibility("default"))) = {total_size};
extern const uint32_t g_vmp_payload_crc32 __attribute__((used, visibility("default"))) = {crc_hex};

extern const uint8_t g_vmp_payload[] __attribute__((used, visibility("default"))) = {{
{payload_str}
}};
'''

    with open(out_path, 'w') as f:
        f.write(content)

    print(f"Written {len(content):,} chars → {out_path}", file=sys.stderr)
    print(f"Config → {cpp_dir / 'g_vmp_config.h'}", file=sys.stderr)


if __name__ == '__main__':
    main()
